"""Generate seed-level and selected-epoch diagnostics from archived runs."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
TABLES = ROOT / "paper" / "tables"
OUTPUT = RESULTS / "seed_epoch_diagnostics.json"
SEEDS = (42, 43, 44)
DATASETS = {
    "bci2a": {"label": "BCI 2a", "epochs": 300},
    "bci2b": {"label": "BCI 2b", "epochs": 300},
    "lee2019": {"label": "Lee2019", "epochs": 200},
    "schirrmeister": {"label": "HGD", "epochs": 200},
}
TEMPLATES = {
    "fixed": (
        "{dataset}_plv_eegnet_shuffle_pairs_fixed_globaltrialid_"
        "exactrandperm_dedicatedrng_seed{seed}_{epochs}ep_propersplit.json"
    ),
    "resampled": (
        "{dataset}_plv_eegnet_shuffle_pairs_train_resampled_eval_fixed_"
        "globaltrialid_exactrandperm_dedicatedrng_seed{seed}_{epochs}ep_"
        "propersplit.json"
    ),
}


def _load(dataset: str, condition: str, seed: int, epochs: int) -> dict:
    path = RESULTS / TEMPLATES[condition].format(
        dataset=dataset, seed=seed, epochs=epochs
    )
    if not path.is_file():
        raise FileNotFoundError(path)
    payload = json.loads(path.read_text())
    if payload["aggregate"]["epochs"] != epochs:
        raise ValueError(f"epoch mismatch: {path}")
    return payload


def _fmt(values: list[float]) -> str:
    return "$" + ",\\; ".join(f"{value:+.2f}" for value in values) + "$"


def main() -> None:
    output = {
        "unit": "percentage points for schedule gaps; epoch for checkpoints",
        "conditions": "resampled-minus-fixed training at deterministic fixed inference",
        "datasets": {},
    }
    seed_rows = []
    epoch_rows = []
    for dataset, spec in DATASETS.items():
        loaded = {
            condition: {
                seed: _load(dataset, condition, seed, spec["epochs"])
                for seed in SEEDS
            }
            for condition in TEMPLATES
        }
        seed_gaps = []
        for seed in SEEDS:
            fixed = np.asarray(
                [row["eval_at_best_val"] for row in loaded["fixed"][seed]["per_subject"]]
            )
            resampled = np.asarray(
                [
                    row["eval_at_best_val"]
                    for row in loaded["resampled"][seed]["per_subject"]
                ]
            )
            if fixed.shape != resampled.shape:
                raise ValueError(f"subject-count mismatch: {dataset}, seed {seed}")
            seed_gaps.append(float(100.0 * np.mean(resampled - fixed)))
        leave_one_out = [
            float(np.mean([gap for index, gap in enumerate(seed_gaps) if index != omit]))
            for omit in range(len(SEEDS))
        ]
        sign = int(np.sign(np.mean(seed_gaps)))
        sign_consistent = sum(int(np.sign(gap) == sign) for gap in seed_gaps)

        epoch_summary = {}
        for condition in TEMPLATES:
            epochs_all = np.asarray(
                [
                    int(row["best_epoch"])
                    for seed in SEEDS
                    for row in loaded[condition][seed]["per_subject"]
                ]
            )
            q1, median, q3 = np.percentile(epochs_all, [25, 50, 75])
            ceiling = int(np.sum(epochs_all == spec["epochs"]))
            epoch_summary[condition] = {
                "median": float(median),
                "q1": float(q1),
                "q3": float(q3),
                "ceiling_count": ceiling,
                "total_runs": int(len(epochs_all)),
                "ceiling_percent": float(100.0 * ceiling / len(epochs_all)),
            }
            epoch_rows.append(
                (
                    spec["label"],
                    condition.capitalize(),
                    f"{median:.0f} [{q1:.0f}, {q3:.0f}]",
                    f"{ceiling}/{len(epochs_all)} ({100.0 * ceiling / len(epochs_all):.1f}\\%)",
                )
            )
        output["datasets"][dataset] = {
            "seed_schedule_gap_pp": dict(zip(map(str, SEEDS), seed_gaps)),
            "leave_one_seed_out_gap_pp": dict(zip(map(str, SEEDS), leave_one_out)),
            "seed_sign_consistency": f"{sign_consistent}/{len(SEEDS)}",
            "selected_epoch": epoch_summary,
        }
        seed_rows.append(
            (
                spec["label"],
                _fmt(seed_gaps),
                _fmt(leave_one_out),
                f"{sign_consistent}/3",
            )
        )

    OUTPUT.write_text(json.dumps(output, indent=2) + "\n")
    TABLES.mkdir(parents=True, exist_ok=True)
    lines = [
        "% Generated by scripts/analyze_seed_epoch_diagnostics.py",
        "\\begin{tabular}{lrrc}",
        "\\toprule",
        "Dataset & Seed gaps 42, 43, 44 (pp) & Leave-one-seed-out gaps (pp) & Sign consistency \\\\",
        "\\midrule",
    ]
    lines.extend(" & ".join(row) + " \\\\" for row in seed_rows)
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    (TABLES / "seed_schedule_diagnostics.tex").write_text("\n".join(lines))

    lines = [
        "% Generated by scripts/analyze_seed_epoch_diagnostics.py",
        "\\begin{tabular}{llc@{\\hspace{2em}}c}",
        "\\toprule",
        "Dataset & Training schedule & Selected epoch, median [IQR] & At epoch ceiling \\\\",
        "\\midrule",
    ]
    lines.extend(" & ".join(row) + " \\\\" for row in epoch_rows)
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    (TABLES / "selected_epoch_diagnostics.tex").write_text("\n".join(lines))
    print(f"written: {OUTPUT}")


if __name__ == "__main__":
    main()
